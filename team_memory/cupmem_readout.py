"""Expand CUPMem-selected memory and its status-cause links to original records.

Uses the existing provenance resolver's output: no new search or full-history
fallback. The final reader uses original passages for details lost in summaries.
"""
import json
from hashlib import sha256
from .core import answer_question
from .store import source_envelope,digest

SOURCE_POLICY = '''The memory_annotations were generated by CUPMem and are not author approvals.
They summarize selected assertions and may omit source details. A STALE label applies to the referenced
assertion, not every fact in its original record. Read the original passages to answer THIS question.
Keep old measurements under their original conditions even when a deployment constraint changes.
Sources marked status_cause explain why a selected memory changed; they are not automatically relevant
to every question. Cite only the original passages that support each answer. Do not cite AI summaries.'''


def source_packet(native_result):
    provenance=native_result.get('provenance')
    if not provenance or provenance['unresolved'] or native_result.get('provenance_errors'):
        raise ValueError('Native-selected provenance must resolve before source expansion')
    records={};uses={}
    for p in provenance['original_turns_for_audit']:
        roles={u['purpose'] for u in p['uses']}
        if not roles or not roles<= {'value','status_cause'}:raise ValueError('unsupported provenance role')
        if sha256(p['text'].encode()).hexdigest()!=p['content_sha256']:raise ValueError('source content hash mismatch')
        env=source_envelope(json.loads(p['text']))
        if p['session_time']!=env['observed_at'] or p['turn_id']!='t_0':raise ValueError('source identity mismatch')
        if p['session_id']!='s_'+str(p['session_index']).zfill(3):raise ValueError('source position mismatch')
        sid=digest(env);records[sid]=env;uses.setdefault(sid,[]).extend(p['uses'])
    if not records:raise ValueError('No selected source evidence; do not fall back to all history')
    annotation=dict(unverified_model_annotations=True,
        selected_bases=[b['native_basis'] for b in provenance['basis_bindings']],
        source_uses=uses,original_turn_scope='selected memory origins plus explicit status-cause lineage')
    return dict(records=list(records.values()),question=native_result['question'],memory_annotations=annotation)


def read_selected_sources(native_result, generate):
    packet=source_packet(native_result)
    def read(system,content):
        body=json.loads(content);body['memory_annotations']=packet['memory_annotations']
        return generate(system+'\n'+SOURCE_POLICY,json.dumps(body,ensure_ascii=False))
    result=answer_question(packet['records'],packet['question'],read)
    return dict(result,native_answer=native_result['answer'],
                readout='CUPMem-selected original sources and status-cause links',
                source_scope=packet['memory_annotations']['source_uses'])
